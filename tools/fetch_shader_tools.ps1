# Downloads the GLSL -> SPIR-V -> HLSL translators used by shader-pack support (src/render/packs): glslang and
# SPIRV-Cross, pinned source releases from the official KhronosGroup GitHub repositories, SHA-256 verified. Only the
# library sources are unpacked (into third_party\glslang and third_party\spirv-cross, git-ignored); CMake builds them
# as static libraries (third_party\shader_tools.cmake). Without them the game builds and runs, packs are unavailable.
# Usage: powershell -File tools\fetch_shader_tools.ps1 [-Force]
param([switch]$Force)
$ErrorActionPreference = "Stop"
$ProgressPreference = "SilentlyContinue"
Add-Type -AssemblyName System.IO.Compression.FileSystem

$root = Split-Path -Parent $PSScriptRoot
$tp = Join-Path $root "third_party"
$cache = Join-Path $root "build\sdk_downloads"
New-Item -ItemType Directory -Force $cache | Out-Null

function Get-Verified([string]$url, [string]$sha256, [string]$file) {
    if ($Force -or -not (Test-Path $file) -or (Get-FileHash -Algorithm SHA256 $file).Hash -ne $sha256.ToUpper()) {
        Write-Host "downloading $url"
        Invoke-WebRequest -UseBasicParsing -Uri $url -OutFile $file
    }
    $h = (Get-FileHash -Algorithm SHA256 $file).Hash
    if ($h -ne $sha256.ToUpper()) { Remove-Item $file; throw "SHA-256 mismatch for $url`n  expected $sha256`n  got      $h" }
    Write-Host "  ok  $([IO.Path]::GetFileName($file))  sha256 $sha256"
}

# Extracts the entries under $top/ whose path (below $top/) matches one of the regexes into $dest.
function Expand-Matching([string]$zip, [string]$top, [string[]]$patterns, [string]$dest) {
    if (Test-Path $dest) { Remove-Item -Recurse -Force $dest }
    $z = [IO.Compression.ZipFile]::OpenRead($zip)
    $n = 0
    try {
        foreach ($e in $z.Entries) {
            if ($e.FullName.EndsWith("/") -or -not $e.FullName.StartsWith("$top/")) { continue }
            $rel = $e.FullName.Substring($top.Length + 1)
            foreach ($p in $patterns) {
                if ($rel -match $p) {
                    $out = Join-Path $dest ($rel -replace '/', '\')
                    New-Item -ItemType Directory -Force (Split-Path $out) | Out-Null
                    [IO.Compression.ZipFileExtensions]::ExtractToFile($e, $out, $true)
                    $n++
                    break
                }
            }
        }
    } finally { $z.Dispose() }
    Write-Host "  $n files -> $dest"
}

$tag = "vulkan-sdk-1.4.357.0"

# ---- glslang (GLSL front end + SPIR-V generator), BSD-3-Clause / mixed permissive (LICENSE.txt) ----
# https://github.com/KhronosGroup/glslang/releases/tag/vulkan-sdk-1.4.357.0 (source archive of the tag)
$gl = Join-Path $cache "glslang-$tag.zip"
Get-Verified "https://github.com/KhronosGroup/glslang/archive/refs/tags/$tag.zip" `
    "4b95c034542b19cdc169b105fb05845b20ff168a80ef8ed721db089753ee7746" $gl
$glDir = Join-Path $tp "glslang"
Expand-Matching $gl "glslang-$tag" @(
    '^LICENSE\.txt$', '^build_info\.h\.tmpl$',
    '^glslang/(Include|Public|GenericCodeGen|ResourceLimits)/[^/]+\.(h|cpp)$',
    '^glslang/MachineIndependent/[^/]+\.(h|cpp)$', '^glslang/MachineIndependent/preprocessor/[^/]+\.(h|cpp)$',
    '^glslang/OSDependent/osinclude\.h$', '^glslang/OSDependent/Windows/ossource\.cpp$',
    '^SPIRV/[^/]+\.(h|cpp|hpp11)$'
) $glDir
# build_info.h (generated by glslang's own CMake normally).
$info = (Get-Content -Raw (Join-Path $glDir "build_info.h.tmpl")) -replace '@major@', '16' -replace '@minor@', '4' `
    -replace '@patch@', '0' -replace '@flavor@', $tag
New-Item -ItemType Directory -Force (Join-Path $glDir "include\glslang") | Out-Null
[IO.File]::WriteAllText((Join-Path $glDir "include\glslang\build_info.h"), $info)

# ---- SPIRV-Cross (SPIR-V -> HLSL), Apache-2.0 (LICENSE) ----
# https://github.com/KhronosGroup/SPIRV-Cross/releases/tag/vulkan-sdk-1.4.357.0 (source archive of the tag)
$sc = Join-Path $cache "SPIRV-Cross-$tag.zip"
Get-Verified "https://github.com/KhronosGroup/SPIRV-Cross/archive/refs/tags/$tag.zip" `
    "e10c3c1651953ed3fc363fc7c2c330e1243f1bf9071118750c1c5a51b1ab29ab" $sc
Expand-Matching $sc "SPIRV-Cross-$tag" @(
    '^LICENSE$', '^GLSL\.std\.450\.h$', '^spirv\.hpp$', '^spirv\.h$', '^NonSemanticShaderDebugInfo100\.h$',
    '^spirv_(common|cross|cross_containers|cross_error_handling|cross_parsed_ir|parser|cfg|glsl|hlsl)\.(hpp|cpp)$'
) (Join-Path $tp "spirv-cross")

Write-Host "shader tools ready in $tp (re-run CMake / build.ps1)"
