Type typeOf(u32 cp) {
    size_t lo = 0, hi = std::size(kRanges);
    while (lo < hi) {
        const size_t mid = (lo + hi) / 2;
        if (cp < kRanges[mid].lo) hi = mid;
        else if (cp > kRanges[mid].hi) lo = mid + 1;
        else return kRanges[mid].type;
    }
    return L;
}

